import { test } from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { randomUUID } from "node:crypto";
import { JSDOM } from "jsdom";
import { createServer } from "vite";
import { sprintTranslations } from "./src/context/sprintTranslations.js";
import { sprint5Translations } from "./src/context/sprint5Translations.js";

test("React -> real HTTP -> isolated PostgreSQL: supplier, brands, product, reload and languages", { timeout: 120000 }, async () => {
  const backendRequire = createRequire(new URL("../backend/package.json", import.meta.url));
  backendRequire("./scripts/sprint5-target.cjs").configureSprint5();
  const { prisma } = backendRequire("./src/lib/prisma");
  const [db] = await prisma.$queryRaw`SELECT current_database() AS name`;
  assert.equal(db.name, "sistema_inventario_sprint5_test");
  const tag = "s5ui_" + randomUUID().slice(0, 8);
  const admin = await prisma.rol.findUnique({ where: { nombre: "Administrador" } });
  const hash = await backendRequire("bcryptjs").hash("S5Ui!Fixture2026", 10);
  const account = await prisma.usuario.create({ data: { nombre: tag, correo: `${tag}@water.cc`, passwordHash: hash, rolId: admin.id } });
  const token = backendRequire("jsonwebtoken").sign({ sub: String(account.id), cv: backendRequire("./src/middleware/auth.middleware").credentialVersion(hash) }, backendRequire("./src/config/env").env.JWT_SECRET, { expiresIn: "1h" });
  const category = await prisma.categoria.create({ data: { nombre: tag + " Category" } });
  const { app } = backendRequire("./src/app");
  const server = app.listen(0, "127.0.0.1"); await new Promise(r => server.once("listening", r));
  const dom = new JSDOM('<div id="root"></div>', { url: "http://localhost:5173/proveedores" });
  for (const key of ["window", "document", "localStorage", "sessionStorage", "HTMLElement", "Event", "KeyboardEvent", "MouseEvent"]) globalThis[key] = dom.window[key];
  Object.defineProperty(globalThis, "navigator", { value: dom.window.navigator, configurable: true });
  globalThis.IS_REACT_ACT_ENVIRONMENT = true;
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  sessionStorage.setItem("lwi_session", JSON.stringify({ token, usuario: { id: String(account.id), nombre: tag, correo: account.correo, rol: { id: String(admin.id), nombre: "Administrador" } } }));
  const originalFetch = globalThis.fetch;
  const writes = [];
  globalThis.fetch = (url, options) => {
    const parsed = new URL(url);
    if (parsed.pathname.startsWith("/api/")) {
      if (options?.method && options.method !== "GET") writes.push({ path: parsed.pathname, method: options.method });
      // Existing isolated records must not become targets of this fixture's UI.
      if ((!options?.method || options.method === "GET") && ["/api/productos", "/api/proveedores", "/api/marcas"].includes(parsed.pathname)) parsed.searchParams.set("buscar", tag);
      return originalFetch(`http://127.0.0.1:${server.address().port}${parsed.pathname}${parsed.search}`, options);
    }
    return originalFetch(url, options);
  };
  const vite = await createServer({ server: { middlewareMode: true, hmr: false }, appType: "custom", ssr: { noExternal: ["react-router-dom", "react-router"], resolve: { conditions: ["module-sync", "import", "development"] } } });
  const React = await import("react"), { act } = React;
  const { createRoot } = await import("react-dom/client"), { Simulate } = await import("react-dom/test-utils");
  const { BrowserRouter } = await vite.ssrLoadModule("react-router-dom");
  const { default: App } = await vite.ssrLoadModule("/src/App.jsx");
  const { AuthProvider } = await vite.ssrLoadModule("/src/context/AuthContext.jsx");
  const { LanguageProvider } = await vite.ssrLoadModule("/src/context/LanguageContext.jsx");
  const root = createRoot(document.getElementById("root"));
  const t = language => ({ ...sprintTranslations[language], ...sprint5Translations[language] });
  const button = text => [...document.querySelectorAll("button")].find(el => el.textContent.trim() === text);
  const field = text => [...document.querySelectorAll("dialog label")].find(el => el.firstChild?.textContent.trim() === text)?.querySelector("input,select,textarea");
  const click = async el => { assert.ok(el, "Button missing"); await act(async () => Simulate.click(el)); };
  const change = async (el, value) => { assert.ok(el, "Field missing"); await act(async () => Simulate.change(el, { target: { value } })); };
  const submit = async el => { assert.ok(el); await act(async () => Simulate.submit(el)); };
  const until = async fn => { for (let i = 0; i < 150; i++) { if (fn()) return; await act(async () => new Promise(r => setTimeout(r, 25))); } assert.ok(fn(), document.querySelector('[role="alert"]')?.textContent || "UI did not settle"); };
  const route = async path => { await act(async () => { window.history.pushState({}, "", path); window.dispatchEvent(new dom.window.PopStateEvent("popstate")); }); };
  let supplierId;
  try {
    await act(async () => root.render(React.createElement(BrowserRouter, null, React.createElement(AuthProvider, null, React.createElement(LanguageProvider, null, React.createElement(App))))));
    await until(() => button(t("es").newSupplier));
    await click(button(t("es").newSupplier));
    await change(field(t("es").type), "person");
    await change(field(t("es").firstName), tag + " Ana"); await change(field(t("es").lastName), "S5TEST apellido");
    await change(field(t("es").postalCode), "00001");
    await change(field(t("es").paymentMethod), "TRANSFERENCIA");
    await act(async () => Simulate.change(document.querySelector("dialog .catalog-checkbox input"), { target: { checked: true } }));
    await change(field(t("es").bankName), "S5TEST banco"); await change(field(t("es").accountName), "S5TEST titular"); await change(field(t("es").accountNumber), "000-S5UI-SECRET");
    await submit(document.querySelector("dialog form"));
    await until(() => !document.querySelector("dialog") && document.querySelector("tbody")?.textContent.includes(tag));
    const supplierRow = await prisma.tercero.findFirst({ where: { persona: { nombres: tag + " Ana" } } }); assert.ok(supplierRow); supplierId = supplierRow.id;
    await route("/"); await route("/proveedores");
    await until(() => document.querySelector("tbody")?.textContent.includes(tag));
    await click(document.querySelector(`tbody button[aria-label="${t("es").edit}"]`));
    await until(() => field(t("es").lastName)?.value === "S5TEST apellido");
    await change(field(t("es").lastName), "S5TEST editado");
    await submit(document.querySelector("dialog form"));
    await until(() => !document.querySelector("dialog") && document.querySelector("tbody")?.textContent.includes("S5TEST editado"));
    await click(document.querySelector(`tbody button[aria-label="${t("es").deactivate}"]`));
    await click(button(t("es").confirm));
    await until(() => !document.querySelector("dialog"));
    assert.equal((await prisma.terceroRol.findUnique({ where: { terceroId_rol: { terceroId: supplierId, rol: "PROVEEDOR" } } })).activo, false);
    for (const language of ["es", "en", "fr"]) {
      await route("/configuracion"); await until(() => document.querySelector(".settings-preferences select"));
      await change(document.querySelector(".settings-preferences select"), language);
      await route("/proveedores"); await until(() => document.querySelector("main h1")?.textContent === t(language).suppliers);
      await click(button(t(language).newSupplier)); await change(field(t(language).type), "company");
      assert.ok(field(t(language).tradeName)); assert.equal(field(t(language).legalName).required, false);
      assert.ok(field(t(language).postalCode));
      await click(document.querySelector("dialog .account-modal-head button"));
    }
    const fr = t("fr");
    await route("/inventario"); await until(() => button(fr.brands)); await click(button(fr.brands));
    await until(() => button(fr.newBrand)); await click(button(fr.newBrand));
    await change(field(fr.brandName), tag + " Brand"); await submit(document.querySelector("dialog form"));
    await until(() => document.querySelector("dialog tbody")?.textContent.includes(tag));
    const brand = await prisma.marca.findFirst({ where: { nombre: tag + " Brand" } }); assert.ok(brand);
    await click(document.querySelector("dialog .account-modal-head button"));
    await click(button(fr.newProduct));
    await until(() => field(fr.brand)?.querySelector(`option[value="${brand.id}"]`));
    await change(field(fr.code), tag + "_P"); await change(field(fr.productName), tag + " Product");
    await change(field(fr.category), String(category.id)); await change(field(fr.brand), String(brand.id)); await change(field(fr.minimum), "1.125");
    assert.equal(field(fr.stock), undefined); assert.equal(field(fr.cost), undefined);
    await submit(document.querySelector("dialog form"));
    await until(() => !document.querySelector("dialog") && document.querySelector("tbody")?.textContent.includes(tag + " Product"));
    const product = await prisma.producto.findUnique({ where: { codigo: tag + "_P" } }); assert.equal(product.marcaId, brand.id);
    await route(`/inventario/${product.id}`);
    await until(() => document.querySelector("dl")?.textContent.includes(tag + " Product"));
    assert.ok(document.querySelector("dl").textContent.includes(tag + " Brand"));
    assert.ok(document.querySelector("main").textContent.includes(fr.stockPending));
    assert.ok(writes.some(call => call.path === "/api/productos" && call.method === "POST"));
    assert.ok(writes.some(call => call.path === "/api/proveedores" && call.method === "POST"));
    assert.ok(writes.some(call => call.path === "/api/marcas" && call.method === "POST"));
  } finally {
    await act(async () => root.unmount()); await vite.close(); globalThis.fetch = originalFetch; dom.window.close();
    await new Promise(r => server.close(r));
    if (process.env.LWI_KEEP_TEST_DATA !== "1") {
      const thirds = await prisma.tercero.findMany({ where: { persona: { nombres: { startsWith: tag } } }, select: { id: true } });
      const ids = thirds.map(t => t.id);
      await prisma.cuentaBancariaTercero.deleteMany({ where: { terceroId: { in: ids } } });
      await prisma.terceroRol.deleteMany({ where: { terceroId: { in: ids } } });
      await prisma.tercero.deleteMany({ where: { id: { in: ids } } });
      await prisma.persona.deleteMany({ where: { nombres: { startsWith: tag } } });
      await prisma.producto.deleteMany({ where: { codigo: { startsWith: tag } } });
      await prisma.marca.deleteMany({ where: { nombre: { startsWith: tag } } });
      await prisma.categoria.delete({ where: { id: category.id } });
      await prisma.usuario.delete({ where: { id: account.id } });
    } else console.log(`Datos de prueba conservados: ${tag}`);
    await prisma.$disconnect();
  }
});
