-- Encabezado de las operaciones fisicas. Las solicitudes y aprobaciones
-- se relacionaran en una fase posterior, sin duplicarlas aqui
CREATE TABLE public.movimientos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR(50) NOT NULL UNIQUE CHECK (length(btrim(numero)) > 0),
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN
    ('ENTRADA','SALIDA','DEVOLUCION','AJUSTE_ENTRADA','AJUSTE_SALIDA')),
  origen VARCHAR(25) NOT NULL CHECK (origen IN
    ('COMPRA','DONACION','INVENTARIO_INICIAL','REQUISICION','DEVOLUCION','AJUSTE','OTRO')),
  estado VARCHAR(12) NOT NULL DEFAULT 'BORRADOR' CHECK (estado IN
    ('BORRADOR','CONFIRMADO','ANULADO')),
  fecha_operacion DATE NOT NULL DEFAULT CURRENT_DATE,
  fecha_documento DATE,
  bodega_id BIGINT NOT NULL REFERENCES public.bodegas(id) ON DELETE RESTRICT,
  tercero_id BIGINT REFERENCES public.terceros(id) ON DELETE RESTRICT,
  movimiento_origen_id BIGINT REFERENCES public.movimientos(id) ON DELETE RESTRICT,
  documento_tipo VARCHAR(60),
  documento_numero VARCHAR(100),
  solicitante_usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  solicitante_nombre VARCHAR(200),  -- fotografia del formulario fisico
  solicitante_posicion VARCHAR(160),
  proyecto_referencia VARCHAR(100),
  clase_coa_id BIGINT REFERENCES public.clases_coa(id) ON DELETE RESTRICT,
  revisado_por_usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  recibido_por_usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  entregado_por_usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  observaciones TEXT,
  creado_por_usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  confirmado_por_usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  confirmado_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_movimientos_referencia_dev CHECK (
    (tipo = 'DEVOLUCION' AND movimiento_origen_id IS NOT NULL AND origen = 'DEVOLUCION') OR
    (tipo <> 'DEVOLUCION' AND movimiento_origen_id IS NULL)
  ),
  CONSTRAINT ck_movimientos_estado_confirmacion CHECK (
    (estado='CONFIRMADO' AND confirmado_at IS NOT NULL AND confirmado_por_usuario_id IS NOT NULL) OR
    (estado <> 'CONFIRMADO' AND confirmado_at IS NULL AND confirmado_por_usuario_id IS NULL)
  ),
  CONSTRAINT ck_movimientos_no_autoreferencia CHECK (movimiento_origen_id IS NULL OR movimiento_origen_id <> id),
  CONSTRAINT ck_movimientos_origen_tipo CHECK (
    (tipo='AJUSTE_ENTRADA' OR tipo='AJUSTE_SALIDA') AND origen='AJUSTE' OR
    tipo='DEVOLUCION' AND origen='DEVOLUCION' OR
    tipo='SALIDA' AND origen IN ('REQUISICION','OTRO') OR
    tipo='ENTRADA' AND origen IN ('COMPRA','DONACION','INVENTARIO_INICIAL','OTRO')
  )
);
CREATE INDEX ix_movimientos_tipo_fecha ON public.movimientos(tipo, fecha_operacion DESC);
CREATE INDEX ix_movimientos_bodega_estado ON public.movimientos(bodega_id, estado);
CREATE INDEX ix_movimientos_tercero ON public.movimientos(tercero_id);
CREATE INDEX ix_movimientos_origen ON public.movimientos(movimiento_origen_id);

-- Detalle de cada movimiento. Varias lineas pueden tener el mismo producto
-- si corresponden a distintos lotes, ubicaciones o vencimientos
CREATE TABLE public.movimiento_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movimiento_id BIGINT NOT NULL REFERENCES public.movimientos(id) ON DELETE RESTRICT,
  producto_id BIGINT NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  ubicacion_id BIGINT REFERENCES public.ubicaciones(id) ON DELETE RESTRICT,
  cantidad NUMERIC(18,3) NOT NULL CHECK (cantidad > 0),
  costo_unitario NUMERIC(18,6) CHECK (costo_unitario IS NULL OR costo_unitario >= 0),
  codigo_lote VARCHAR(100),
  fecha_vencimiento DATE,
  observaciones TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_movimiento_detalle_identidad UNIQUE (id, movimiento_id, producto_id)
);
CREATE INDEX ix_movimiento_detalles_mov ON public.movimiento_detalles(movimiento_id);
CREATE INDEX ix_movimiento_detalles_producto ON public.movimiento_detalles(producto_id);

-- Una linea de entrada confirmada origina exactamente un lote
-- Cantidad disponible se actualiza solo por funciones de confirmacion
CREATE TABLE public.lotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrada_detalle_id BIGINT NOT NULL UNIQUE REFERENCES public.movimiento_detalles(id) ON DELETE RESTRICT,
  producto_id BIGINT NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  bodega_id BIGINT NOT NULL REFERENCES public.bodegas(id) ON DELETE RESTRICT,
  ubicacion_id BIGINT REFERENCES public.ubicaciones(id) ON DELETE RESTRICT,
  codigo_lote VARCHAR(100),
  fecha_recepcion DATE NOT NULL,
  fecha_vencimiento DATE,
  cantidad_inicial NUMERIC(18,3) NOT NULL CHECK (cantidad_inicial > 0),
  cantidad_disponible NUMERIC(18,3) NOT NULL,
  costo_unitario NUMERIC(18,6) NOT NULL CHECK (costo_unitario >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_lotes_saldo CHECK (cantidad_disponible BETWEEN 0 AND cantidad_inicial)
);
CREATE INDEX ix_lotes_peps ON public.lotes(producto_id,bodega_id,fecha_recepcion,id)
  WHERE cantidad_disponible > 0;
CREATE INDEX ix_lotes_vencimiento ON public.lotes(fecha_vencimiento)
  WHERE fecha_vencimiento IS NOT NULL AND cantidad_disponible > 0;

-- Una linea de salida puede consumir varios lotes: costo historico congelado
CREATE TABLE public.consumos_lote (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salida_detalle_id BIGINT NOT NULL REFERENCES public.movimiento_detalles(id) ON DELETE RESTRICT,
  lote_id BIGINT NOT NULL REFERENCES public.lotes(id) ON DELETE RESTRICT,
  cantidad NUMERIC(18,3) NOT NULL CHECK (cantidad > 0),
  costo_unitario NUMERIC(18,6) NOT NULL CHECK (costo_unitario >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_consumos_lote UNIQUE (salida_detalle_id,lote_id)
);
CREATE INDEX ix_consumos_lote_lote ON public.consumos_lote(lote_id);

-- En BORRADOR se declara de qué consumo provienen las unidades devueltas
-- La función de confirmación valida la suma, las cantidades ya devueltas,
-- el producto, el almacén y asigna su costo histórico original
CREATE TABLE public.devoluciones_lote (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  devolucion_detalle_id BIGINT NOT NULL REFERENCES public.movimiento_detalles(id) ON DELETE RESTRICT,
  consumo_lote_id BIGINT NOT NULL REFERENCES public.consumos_lote(id) ON DELETE RESTRICT,
  cantidad NUMERIC(18,3) NOT NULL CHECK (cantidad > 0),
  costo_unitario NUMERIC(18,6) CHECK (costo_unitario IS NULL OR costo_unitario >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_devoluciones_consumo UNIQUE (devolucion_detalle_id, consumo_lote_id)
);
CREATE INDEX ix_devoluciones_consumo ON public.devoluciones_lote(consumo_lote_id);

COMMENT ON TABLE public.movimientos IS 'Operacion documental; no equivale a stock hasta su confirmacion';
COMMENT ON TABLE public.movimiento_detalles IS 'Lineas de productos, cantidades y datos de ingreso';
COMMENT ON TABLE public.lotes IS 'Existencias por recepcion, costo y ubicacion. Orden PEPS: fecha_recepcion,id';
COMMENT ON TABLE public.consumos_lote IS 'Asignacion PEPS de cada salida a lotes concretos';
COMMENT ON TABLE public.devoluciones_lote IS 'Reincorporacion de unidades consumidas originalmente, con su costo';
COMMENT ON COLUMN public.movimiento_detalles.costo_unitario IS 'Obligatorio al confirmar entradas y ajustes de entrada; no inventar costos historicos';

COMMIT;
