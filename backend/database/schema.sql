    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_bodegas_codigo_ci ON public.bodegas(upper(btrim(codigo)));

-- 13) Ubicaciones dentro de una bodega (pasillo, estante, zona, etc.).
CREATE TABLE IF NOT EXISTS public.ubicaciones (
