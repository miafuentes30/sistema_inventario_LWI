    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_ubicaciones_bodega_codigo UNIQUE (bodega_id, codigo)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ubicaciones_bodega_codigo_ci
    ON public.ubicaciones (bodega_id, upper(btrim(codigo)));

-- Mantenimiento automatico de updated_at.
CREATE OR REPLACE FUNCTION public.lwi_fase1_actualizar_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;
DO $$
DECLARE nombre_tabla TEXT;
BEGIN
    FOREACH nombre_tabla IN ARRAY ARRAY[
       'personas','empresas','terceros','tercero_roles',
       'categorias','subcategorias','unidades_medida','marcas',
       'clases_coa','productos','tercero_productos','bodegas','ubicaciones'
    ] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', 'trg_lwi_fase1_updated_at', nombre_tabla);
        EXECUTE format(
            'CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.lwi_fase1_actualizar_updated_at()',
            'trg_lwi_fase1_updated_at', nombre_tabla
        );
    END LOOP;
END;
$$;

