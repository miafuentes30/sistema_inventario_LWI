CREATE INDEX IF NOT EXISTS ix_tercero_productos_producto ON public.tercero_productos(producto_id);

-- 12) Bodegas; no se presupone cantidad ni nombre de bodegas de LWI.
CREATE TABLE IF NOT EXISTS public.bodegas (
