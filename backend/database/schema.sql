BEGIN;

-- 1) Personas: proveedores/donantes individuales y propietarios de empresas individuales.
CREATE TABLE IF NOT EXISTS public.personas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(120) NOT NULL CHECK (length(btrim(nombres)) > 0),
    apellidos VARCHAR(120) NOT NULL CHECK (length(btrim(apellidos)) > 0),
    nit VARCHAR(25),
    telefono VARCHAR(40),
    correo VARCHAR(180),
    direccion TEXT,
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_personas_nit_no_vacio CHECK (nit IS NULL OR length(btrim(nit)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_personas_nit_normalizado
    ON public.personas (upper(replace(btrim(nit), '-', '')))
    WHERE nit IS NOT NULL;

-- 2) Empresas: persona juridica o empresa mercantil individual.
-- Para INDIVIDUAL se requiere propietario registrado en personas.
CREATE TABLE IF NOT EXISTS public.empresas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_comercial VARCHAR(200) NOT NULL CHECK (length(btrim(nombre_comercial)) > 0),
    razon_social VARCHAR(250) NOT NULL CHECK (length(btrim(razon_social)) > 0),
    tipo_empresa VARCHAR(12) NOT NULL,
    forma_juridica VARCHAR(100),
    propietario_persona_id BIGINT REFERENCES public.personas(id) ON DELETE RESTRICT,
    nit VARCHAR(25),
    telefono VARCHAR(40),
    correo VARCHAR(180),
    direccion TEXT,
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_empresas_tipo CHECK (tipo_empresa IN ('INDIVIDUAL', 'JURIDICA')),
    CONSTRAINT ck_empresas_propietario CHECK (
        (tipo_empresa = 'INDIVIDUAL' AND propietario_persona_id IS NOT NULL)
        OR (tipo_empresa = 'JURIDICA' AND propietario_persona_id IS NULL)
    ),
    CONSTRAINT ck_empresas_nit_no_vacio CHECK (nit IS NULL OR length(btrim(nit)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_empresas_nit_normalizado
    ON public.empresas (upper(replace(btrim(nit), '-', '')))
    WHERE nit IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_empresas_propietario ON public.empresas(propietario_persona_id);

-- 3) Terceros: referenciar exactamente una persona O una empresa.
CREATE TABLE IF NOT EXISTS public.terceros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_id BIGINT UNIQUE REFERENCES public.personas(id) ON DELETE RESTRICT,
    empresa_id BIGINT UNIQUE REFERENCES public.empresas(id) ON DELETE RESTRICT,
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_terceros_entidad_exclusiva CHECK (
        (persona_id IS NOT NULL) <> (empresa_id IS NOT NULL)
    )
);

-- 4) Un tercero puede ser proveedor, donante o ambas cosas.
CREATE TABLE IF NOT EXISTS public.tercero_roles (
    tercero_id BIGINT NOT NULL REFERENCES public.terceros(id) ON DELETE RESTRICT,
    rol VARCHAR(15) NOT NULL CHECK (rol IN ('PROVEEDOR', 'DONANTE')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (tercero_id, rol)
);

-- 5) Categorias de inventario; se cargan fieles a la hoja Stock.
CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) UNIQUE,
    nombre VARCHAR(200) NOT NULL UNIQUE CHECK (length(btrim(nombre)) > 0),
    descripcion TEXT,
    pendiente_revision BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_categorias_nombre_ci ON public.categorias (lower(btrim(nombre)));

-- 6) Subcategorias por categoria, sin valores ficticios inicialmente.
CREATE TABLE IF NOT EXISTS public.subcategorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES public.categorias(id) ON DELETE RESTRICT,
    codigo VARCHAR(40),
    nombre VARCHAR(200) NOT NULL CHECK (length(btrim(nombre)) > 0),
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_subcategorias_id_categoria UNIQUE (id, categoria_id),
    CONSTRAINT uq_subcategorias_categoria_nombre UNIQUE (categoria_id, nombre),
    CONSTRAINT uq_subcategorias_categoria_codigo UNIQUE (categoria_id, codigo)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_subcategorias_nombre_ci
    ON public.subcategorias (categoria_id, lower(btrim(nombre)));

-- 7) Unidades de medida: se definen con LWI, no se adivinan del texto de descripcion.
CREATE TABLE IF NOT EXISTS public.unidades_medida (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE CHECK (length(btrim(codigo)) > 0),
    nombre VARCHAR(100) NOT NULL UNIQUE CHECK (length(btrim(nombre)) > 0),
    simbolo VARCHAR(20),
    permite_fracciones BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_unidades_medida_codigo_ci ON public.unidades_medida (upper(btrim(codigo)));

-- 8) Marcas.
CREATE TABLE IF NOT EXISTS public.marcas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL UNIQUE CHECK (length(btrim(nombre)) > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_marcas_nombre_ci ON public.marcas (lower(btrim(nombre)));

-- 9) Clasificador contable COA-LWI (no confundir con categoria fisica).
CREATE TABLE IF NOT EXISTS public.clases_coa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE CHECK (length(btrim(codigo)) > 0),
    nombre VARCHAR(200),
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 10) Productos: catalogo SIN cantidad, saldo ni costo vigente.
-- El precio real, costo y saldo se guardaran en lotes/movimientos (fases posteriores).
CREATE TABLE IF NOT EXISTS public.productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL UNIQUE CHECK (length(btrim(codigo)) > 0),
    nombre VARCHAR(255) NOT NULL CHECK (length(btrim(nombre)) > 0),
    descripcion TEXT,
    categoria_id BIGINT NOT NULL REFERENCES public.categorias(id) ON DELETE RESTRICT,
    subcategoria_id BIGINT,
    unidad_medida_id BIGINT REFERENCES public.unidades_medida(id) ON DELETE RESTRICT,
    marca_id BIGINT REFERENCES public.marcas(id) ON DELETE RESTRICT,
    clase_coa_id BIGINT REFERENCES public.clases_coa(id) ON DELETE RESTRICT,
    es_perecedero BOOLEAN,
    requiere_vencimiento BOOLEAN,
    stock_minimo NUMERIC(18,3) CHECK (stock_minimo IS NULL OR stock_minimo >= 0),
    fuente_importacion VARCHAR(160),
    pendiente_revision BOOLEAN NOT NULL DEFAULT TRUE,
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_productos_subcategoria_categoria FOREIGN KEY (subcategoria_id, categoria_id)
        REFERENCES public.subcategorias(id, categoria_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_productos_codigo_ci ON public.productos (upper(btrim(codigo)));
CREATE INDEX IF NOT EXISTS ix_productos_categoria ON public.productos(categoria_id);
CREATE INDEX IF NOT EXISTS ix_productos_subcategoria ON public.productos(subcategoria_id);
CREATE INDEX IF NOT EXISTS ix_productos_unidad ON public.productos(unidad_medida_id);
CREATE INDEX IF NOT EXISTS ix_productos_clase_coa ON public.productos(clase_coa_id);

-- 11) Relacion comercial opcional producto<->proveedor/donante.
-- La FK compuesta obliga a que el rol ya este dado de alta en tercero_roles.
CREATE TABLE IF NOT EXISTS public.tercero_productos (
    tercero_id BIGINT NOT NULL,
    rol VARCHAR(15) NOT NULL,
    producto_id BIGINT NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
    codigo_catalogo_tercero VARCHAR(100),
    observaciones TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (tercero_id, rol, producto_id),
    CONSTRAINT fk_tercero_productos_rol FOREIGN KEY (tercero_id, rol)
        REFERENCES public.tercero_roles(tercero_id, rol) ON DELETE RESTRICT
